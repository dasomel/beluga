import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";
import { POLICY_OPERATION_ACCESS_TYPE } from "../packages/policy-compiler/src/accessType.js";
import { compileAll } from "../packages/policy-compiler/src/compiler/index.js";
import { declarationSchema } from "../packages/policy-compiler/src/schema.js";
import type { PolicyPermission, PolicyProjection } from "../packages/domain-api/src/schema/policy.js";

export function generateOverviewPolicy(root = new URL("../../", import.meta.url)): PolicyProjection {
  const inputs = ["roles", "groups", "resources", "catalog", "logins"].filter((name) => existsSync(new URL(`policies/${name}.yaml`, root))).map((name) => readFileSync(new URL(`policies/${name}.yaml`, root), "utf8"));
  const declaration = declarationSchema.parse(Object.assign({}, ...inputs.map((input) => parse(input))));
  const compiled = compileAll(declaration);
  const hash = (content: string) => `sha256:${createHash("sha256").update(content).digest("hex")}`;
  // D365-2: compile real declarations at build preparation, not in the API process. Cost:
  // rebuild after policy changes; drift test gates the snapshot. Escape hatch: a runtime policy reader.
  const rego = readFileSync(new URL("gitops/charts/beluga-platform/files/opa/trino.rego", root), "utf8");
  const sql = readFileSync(new URL("gitops/charts/beluga-data/files/db-roles.sql", root), "utf8");
  const body = sql.match(/^-- BEGIN GENERATED BODY[^\n]*\n([\s\S]*?)^-- END GENERATED BODY/m)?.[1];
  if (rego !== compiled.rego || body?.trim() !== compiled.pgddl.trim()) throw new Error("deployed policy artifact drift");
  return {
    id: "beluga-platform-policy", name: "Beluga Platform Policy", version: hash(inputs.join("\n")),
    description: "Build-time projection of GitOps policy declarations; deployment sync is not measured here.",
    sourceFile: "policies/{roles,groups,resources,catalog,logins}.yaml",
    // Content-addressed build snapshot has no invented deployment observation time.
    evaluatedAt: "1970-01-01T00:00:00.000Z",
    roles: declaration.roles.map((role) => {
      const permissions: PolicyPermission[] = [];
      for (const resource of declaration.resources) for (const grant of resource.grants) {
        if (!grant.roles.includes(role.name)) continue;
        for (const operation of grant.privileges) permissions.push({
          resource: resource.resource, catalog: resource.engine === "postgres" ? "postgres" : "iceberg",
          engine: resource.engine ?? "trino", operation, accessType: POLICY_OPERATION_ACCESS_TYPE[operation],
          ...(grant.columnMask === undefined ? {} : { columnMask: grant.columnMask }),
          ...(grant.rowFilter === undefined ? {} : { rowFilter: grant.rowFilter }),
          ...(grant.allowUnmasked === undefined ? {} : { allowUnmasked: grant.allowUnmasked }),
        });
      }
      for (const grant of declaration.catalogGrants ?? []) if (grant.roles.includes(role.name)) {
        for (const operation of grant.operations) permissions.push({ resource: `${grant.catalog}.*`, catalog: grant.catalog,
          engine: "trino", operation, accessType: POLICY_OPERATION_ACCESS_TYPE[operation] });
      }
      return { name: role.name, includes: role.includes ?? [], permissions };
    }),
    groups: declaration.groups.map(({ name, roles }) => ({ name, roles })),
    artefacts: ([ ["trino-rego", compiled.rego], ["postgres-grant", compiled.pgddl],
      ["keycloak-mapper", JSON.stringify(compiled.keycloak, null, 2)] ] as const).map(([target, content]) =>
      ({ target, contentHash: hash(content), lineCount: content.split(/\r?\n/).length })),
  };
}

export function generatedPolicyModule() {
  return '// Generated by scripts/generate-overview-policy.ts; do not edit. D365-2.\n' +
    'import type { PolicyProjection } from "../schema/policy.js";\n' +
    `export const overviewPolicy: PolicyProjection = ${JSON.stringify(generateOverviewPolicy())};\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL("../packages/domain-api/src/adapters/overviewPolicy.generated.ts", import.meta.url), generatedPolicyModule());
}
